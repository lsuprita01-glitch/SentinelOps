
import os
from dotenv import load_dotenv
from groq import Groq

load_dotenv()


def predict_attack_stages(incident, historical_memories):

    print("\n========== PREDICTION AGENT ==========")
    print("Analysing possible future attack stages...")

    api_key = os.getenv("GROQ_API_KEY")

    if not api_key:
        raise ValueError("Groq API key is missing.")

    client = Groq(api_key=api_key)

    # Build verified facts directly from the incident.
    verified_facts = [
        f"Incident ID: {incident.get('incident_id', 'Not supplied')}",
        f"Incident type: {incident.get('type', 'Not supplied')}",
        f"Failed attempts: {incident.get('failed_attempts', 'Not supplied')}",
        f"Time window: {incident.get('time_window_minutes', 'Not supplied')} minutes",
        f"Target account: {incident.get('target', 'Not supplied')}",
        f"Unfamiliar IP indicator reported: {incident.get('unfamiliar_ip', 'Not supplied')}",
        f"Successful login recorded in supplied data: {incident.get('successful_login', 'Not supplied')}",
        f"Environment: {incident.get('environment', 'Not supplied')}"
    ]

    facts_section = "\n".join(
        f"- {fact}" for fact in verified_facts
    )

    # Keep historical information separate.
    memory_section = "\n".join(
        f"- {memory}" for memory in historical_memories
    )

    prompt = f"""
You are the Prediction Agent of SentinelOps,
an AI-powered cybersecurity command centre.

Your task is to identify plausible future attack stages
using the supplied incident and historical memories.

VERIFIED CURRENT INCIDENT FACTS:
{facts_section}

HISTORICAL MEMORIES:
{memory_section}

MANDATORY EVIDENCE RULES:

1. Never invent incident facts.

2. An unfamiliar_ip indicator only means that an
   unfamiliar IP was reported in the supplied data.
   It does NOT prove that the IP was never seen before
   for a particular user.

3. A successful_login value of False means that no
   successful login is recorded in the supplied event data.
   Do not claim that every authentication attempt failed
   outside the supplied records.

4. Historical MFA configuration does not prove that
   MFA is enabled in the current incident.

5. Historical events must never be presented as
   verified current incident facts.

6. Do not claim that malware, lateral movement,
   phishing, credential theft or data exfiltration
   has occurred without direct evidence.

7. All future attack stages must be labelled HYPOTHESES.

8. Clearly explain the evidence, missing evidence
   and confidence level for each hypothesis.

9. If information is unavailable, say UNKNOWN.
   Do not fill gaps using assumptions.

OUTPUT FORMAT:

SECTION 1: VERIFIED CURRENT FACTS
Repeat only the supplied incident facts.
Do not add interpretations.

SECTION 2: HISTORICAL MEMORY
Summarise relevant past incidents separately.
Explain that historical events do not prove current activity.

SECTION 3: POSSIBLE NEXT ATTACK STAGES

Provide up to five hypotheses.

For each hypothesis include:
- Hypothesis description
- Reason for considering it
- Available supporting evidence
- Missing evidence
- Confidence: Low, Medium or High

SECTION 4: INDICATORS TO MONITOR
Suggest defensive indicators analysts can monitor.

SECTION 5: INVESTIGATION PRIORITIES
List the most important missing evidence
that analysts should collect next.

SECTION 6: PREDICTION LIMITATIONS
Clearly explain what cannot be concluded
from the supplied incident data.

Remember:
You are predicting possibilities, not reporting
confirmed attacks.
All recommendations must remain defensive.
"""

    try:
        response = client.chat.completions.create(
            model="openai/gpt-oss-120b",
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a cautious cybersecurity "
                        "prediction specialist. Evidence accuracy "
                        "and separation of facts from hypotheses "
                        "are mandatory."
                    )
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            temperature=0.2,
            max_completion_tokens=1800
        )

        ai_predictions = response.choices[0].message.content

        # Assemble the report with facts generated by Python,
        # not by the language model.
        report = f"""
========== VERIFIED CURRENT FACTS ==========

{facts_section}

========== HISTORICAL MEMORY ==========

{memory_section}

========== AI-GENERATED PREDICTIONS ==========

{ai_predictions}

========== PREDICTION SAFETY NOTICE ==========

Future attack stages are hypotheses, not confirmed events.
Historical memories do not establish current incident facts.
Additional evidence is required before drawing conclusions.
"""

        print("\nPREDICTION RESULTS:\n")
        print(report)

        return report

    finally:
        client.close()
